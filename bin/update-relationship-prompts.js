// Run from the repository root after editing relationshipPromptDefaults.js.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { RELATIONSHIP_DEFAULTS } from '../relationshipPromptDefaults.js';

const legacy = JSON.parse(readFileSync('test-fixtures/legacy-status-prompts.json', 'utf8'));
const signatures = { prompt: {}, responseFormat: {}, sections: {} };
const normalize = text => text.replace(/\r\n?/g, '\n').split('\n').map(line => line.trim()).join('\n').trim();
const hash = text => createHash('sha256').update(normalize(text)).digest('hex');
for (const entry of legacy) {
    for (const field of ['prompt', 'responseFormat']) {
        if (entry[field]) signatures[field][hash(entry[field])] = entry.locale;
    }
    const blocks = entry.responseFormat.split(/(?=^###)/m).filter(block => block.startsWith('###'));
    // Upstream ordering: affinity, factors (one or two blocks), relationship,
    // goals, analysis, wrap-up. The short French format has no scoring blocks.
    if (blocks.length < 6) continue;
    const replacements = blocks.length === 7
        ? { 0: 0, 1: 1, 2: -1, 3: 2, 5: 4 }
        : { 0: 0, 1: 1, 2: 2, 4: 4 };
    for (const [index, section] of Object.entries(replacements)) {
        signatures.sections[hash(blocks[index])] = { locale: entry.locale, section };
    }
}
writeFileSync('relationshipPromptLegacy.js', '// Copyright (C) 2024–2026 Aiko Hanasaki\n// SPDX-License-Identifier: AGPL-3.0-only\n// Generated by bin/update-relationship-prompts.js. Recognition hashes only;\n// obsolete instructions are retained solely in test fixtures, never sent to a model.\nexport const LEGACY_STATUS_SIGNATURES = ' + JSON.stringify(signatures, null, 4) + ';\n');

function updateJsonValues(path, changes) {
    let source = readFileSync(path, 'utf8');
    for (const [key, value] of Object.entries(changes)) {
        const pattern = new RegExp('("' + key + '"\\s*:\\s*)"(?:[^"\\\\]|\\\\.)*"');
        if (!pattern.test(source)) throw new Error(`Missing ${key} in ${path}`);
        source = source.replace(pattern, (_, prefix) => prefix + JSON.stringify(value));
    }
    writeFileSync(path, source);
}
for (const file of readdirSync('locales').filter(file => file.endsWith('.json'))) {
    const data = JSON.parse(readFileSync(`locales/${file}`, 'utf8'));
    if (!data.STMemoryBooks_StatusPrompt) continue;
    const locale = file.startsWith('zh-') ? file.slice(0, -5) : file.split('-')[0];
    const defaults = RELATIONSHIP_DEFAULTS[locale];
    if (!defaults) throw new Error(`Missing neutral Status translation: ${locale}`);
    updateJsonValues(`locales/${file}`, {
        STMemoryBooks_StatusPrompt: defaults.prompt,
        STMemoryBooks_StatusResponseFormat: defaults.responseFormat,
    });
}
for (const file of readdirSync('resources/prompts').filter(file => file.startsWith('side-prompts-'))) {
    updateStatus(`resources/prompts/${file}`, file.slice('side-prompts-'.length, -5));
}
updateStatus('resources/SidePromptTemplateLibrary.json', 'en');

function updateStatus(path, locale) {
    const source = readFileSync(path, 'utf8');
    const data = JSON.parse(source);
    const defaults = RELATIONSHIP_DEFAULTS[locale];
    let updated = source;
    for (const field of ['prompt', 'responseFormat']) {
        const oldValue = JSON.stringify(data.prompts.status[field]);
        if (!updated.includes(oldValue)) throw new Error(`Cannot locate Status ${field}: ${path}`);
        updated = updated.replace(oldValue, () => JSON.stringify(defaults[field]));
    }
    writeFileSync(path, updated);
}
console.log('Updated neutral Status translations, template packs, and legacy recognition hashes.');
